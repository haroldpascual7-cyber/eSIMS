                                r.RelativeItem().Text($"• Active Suspensions: {data.ActiveSuspensionsCount}").FontSize(10);
                            });
                        });

                        if (flags.IsIncidentVolumeIncluded)
                        {
                            col.Item().PaddingBottom(12).Column(sc =>
                            {
                                sc.Item().Text("1. Incident Volume & Category Distribution").FontSize(12).Bold().FontColor(Colors.Grey.Darken3);
