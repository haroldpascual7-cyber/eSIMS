        public void GenerateExecutiveSummaryPdf(string filePath, ExecutiveReportData data, ExecutiveReportFlags flags)
        {
            if (data == null) throw new ArgumentNullException(nameof(data));
            if (flags == null) throw new ArgumentNullException(nameof(flags));

            Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(1.5f, Unit.Centimetre);
                    page.PageColor(Colors.White);

                    page.Header().Column(col =>
                    {
                        col.Item().Text("SMART SCHOOL ACADEMY - BOARD OF DIRECTORS").FontSize(18).Bold().FontColor(Colors.Blue.Darken3);
                        col.Item().Text($"EXECUTIVE SAFETY & DISCIPLINE REPORT ({data.TimeframeText.ToUpper()})").FontSize(12).Bold().FontColor(Colors.Grey.Darken3);
                        col.Item().PaddingTop(4).Text($"Generated on: {data.GeneratedDate:yyyy-MM-dd HH:mm:ss} • Period: {data.PeriodType}").FontSize(9).Italic().FontColor(Colors.Grey.Medium);
                        col.Item().PaddingTop(6).LineHorizontal(1).LineColor(Colors.Blue.Darken3);
                    });

                    page.Content().PaddingVertical(10).Column(col =>
                    {
                        col.Item().PaddingBottom(14).Border(1).BorderColor(Colors.Grey.Lighten2).Background(Colors.Grey.Lighten5).Padding(12).Column(c =>
                        {
                            c.Item().Text("EXECUTIVE BRIEFING SUMMARY").FontSize(11).Bold().FontColor(Colors.Blue.Darken3);
                            c.Item().PaddingTop(6).Row(r =>
                            {
                                r.RelativeItem().Text($"• Total Incidents: {data.TotalIncidents}").FontSize(10).Bold();
                                r.RelativeItem().Text($"• Top Offense: {data.TopInfractionCategory}").FontSize(10);
                            });
                            c.Item().PaddingTop(4).Row(r =>
                            {
                                r.RelativeItem().Text($"• High-Risk Location: {data.TopDangerLocation}").FontSize(10);
                                r.RelativeItem().Text($"• Recidivism Rate: {data.RecidivismRatePercent}%").FontSize(10).Bold().FontColor(Colors.Red.Darken2);
