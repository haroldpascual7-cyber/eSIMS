        public void GenerateOverdueComplianceReport(string filePath, List<AcknowledgmentLog> overdueRecords)
        {
            if (overdueRecords == null) throw new ArgumentNullException(nameof(overdueRecords));

            Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(1.5f, Unit.Centimetre);
                    page.PageColor(Colors.White);

                    page.Header().Column(col =>
                    {
                        col.Item().Text("SMART SCHOOL ACADEMY - DISCIPLINE OFFICE").FontSize(18).Bold().FontColor(Colors.Red.Darken2);
                        col.Item().Text("OVERDUE PARENT ACKNOWLEDGMENTS & COMPLIANCE REPORT").FontSize(12).Bold().FontColor(Colors.Grey.Darken3);
                        col.Item().PaddingTop(4).Text($"Generated on: {DateTime.Now:yyyy-MM-dd HH:mm:ss}").FontSize(9).Italic().FontColor(Colors.Grey.Medium);
                        col.Item().PaddingTop(6).LineHorizontal(1).LineColor(Colors.Red.Darken2);
                    });

                    page.Content().PaddingVertical(10).Column(col =>
                    {
                        col.Item().PaddingBottom(10).Text($"Total Overdue Non-Compliant Notices: {overdueRecords.Count}").FontSize(11).Bold().FontColor(Colors.Red.Darken3);

                        col.Item().Table(table =>
                        {
                            table.ColumnsDefinition(columns =>
                            {
                                columns.ConstantColumn(100);
                                columns.RelativeColumn(2);
                                columns.ConstantColumn(90);
                                columns.ConstantColumn(90);
                                columns.ConstantColumn(90);
                            });

                            table.Header(header =>
                            {
                                header.Cell().Background(Colors.Red.Darken2).Padding(5).Text("Notice ID").Bold().FontColor(Colors.White).FontSize(9);
                                header.Cell().Background(Colors.Red.Darken2).Padding(5).Text("Student Name").Bold().FontColor(Colors.White).FontSize(9);
                                header.Cell().Background(Colors.Red.Darken2).Padding(5).Text("Issue Date").Bold().FontColor(Colors.White).FontSize(9);
                                header.Cell().Background(Colors.Red.Darken2).Padding(5).Text("Compliance Due").Bold().FontColor(Colors.White).FontSize(9);
                                header.Cell().Background(Colors.Red.Darken2).Padding(5).Text("Days Overdue").Bold().FontColor(Colors.White).FontSize(9);
                            });

                            for (int i = 0; i < overdueRecords.Count; i++)
                            {
                                var rec = overdueRecords[i];
                                string bg = i % 2 == 0 ? Colors.White : Colors.Grey.Lighten4;

                                int daysOverdue = 0;
                                if (DateTime.TryParse(rec.DueDate, out var dt))
                                {
                                    daysOverdue = Math.Max(0, (DateTime.Today - dt).Days);
                                }

                                table.Cell().Background(bg).Padding(5).Text(rec.NoticeId).FontSize(9).Bold().FontColor(Colors.Blue.Darken2);
                                table.Cell().Background(bg).Padding(5).Text(rec.StudentName).FontSize(9).Bold();
                                table.Cell().Background(bg).Padding(5).Text(rec.IssueDate).FontSize(9);
                                table.Cell().Background(bg).Padding(5).Text(rec.DueDate).FontSize(9);
                                table.Cell().Background(bg).Padding(5).Text($"{daysOverdue} Days").FontSize(9).Bold().FontColor(Colors.Red.Darken2);
                            }
                        });
                    });

                    page.Footer().Column(col =>
                    {
                        col.Item().LineHorizontal(0.5f).LineColor(Colors.Grey.Lighten1);
                        col.Item().PaddingTop(4).Row(row =>
                        {
                            row.RelativeItem().Text("Generated by Smart School Incident Management System • Official Audit Record").FontSize(8).FontColor(Colors.Grey.Medium);
                            row.RelativeItem().AlignRight().Text(txt =>
                            {
                                txt.Span("Page ");
                                txt.CurrentPageNumber();
                                txt.Span(" of ");
                                txt.TotalPages();
                            });
                        });
                    });
                });
            }).GeneratePdf(filePath);
        }

